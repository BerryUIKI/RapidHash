use rapidhash_core::{resolve_manifest_path, AlgorithmId};
use rapidhash_formats::{
    format_gnu_manifest, format_sfv_manifest, parse_gnu_manifest, parse_sfv_manifest, FormatError,
};
use std::path::Path;

#[test]
fn parse_and_format_gnu_canonical() {
    let manifest_text = r#"
# SHA256 test manifest
e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855  empty.txt
ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad  subdir/abc.txt
"#;

    let entries = parse_gnu_manifest(manifest_text, Some(AlgorithmId::Sha256))
        .expect("should parse canonical GNU manifest");

    assert_eq!(entries.len(), 2);
    assert_eq!(entries[0].path_str, "empty.txt");
    assert_eq!(entries[0].line_number, 3);
    assert_eq!(
        entries[0].digest.to_hex_lowercase(),
        "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
    );

    assert_eq!(entries[1].path_str, "subdir/abc.txt");
    assert_eq!(entries[1].line_number, 4);

    let formatted = format_gnu_manifest(&entries);
    assert!(formatted
        .contains("e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855  empty.txt\n"));
    assert!(formatted.contains(
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad  subdir/abc.txt\n"
    ));
}

